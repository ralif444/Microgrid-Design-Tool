"""Generate the OpenAPI description and the frontend TypeScript types (WP 1.1.5, NFR-15).

Usage: python tools/gen.py           write openapi.json and frontend/api-types/schema.d.ts
       python tools/gen.py --check   exit 1 if either generated file is out of date
"""

from __future__ import annotations

import subprocess
import sys
import tempfile
from pathlib import Path

from _common import BACKEND, FRONTEND, node_bin, node_env, uv

OPENAPI = BACKEND / "openapi" / "openapi.json"
TYPES = FRONTEND / "api-types" / "schema.d.ts"
HEADER = "// GENERATED by tools/gen.py from backend/openapi/openapi.json. Do not edit.\n"

DUMP = (
    "import json,sys;from mgapp.main import create_app;"
    "sys.stdout.write(json.dumps(create_app(serve_static=False).openapi(),"
    "indent=2,sort_keys=True,ensure_ascii=False)+'\\n')"
)


def openapi_text() -> str:
    out = subprocess.run(
        [uv(), "run", "--project", str(BACKEND), "python", "-c", DUMP],
        cwd=BACKEND,
        capture_output=True,
        text=True,
        check=True,
    )
    return out.stdout


def types_text(openapi_path: Path) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "schema.d.ts"
        subprocess.run(
            [node_bin("openapi-typescript"), str(openapi_path), "-o", str(out)],
            cwd=FRONTEND,
            env=node_env(),
            check=True,
            capture_output=True,
        )
        return HEADER + out.read_text(encoding="utf-8")


def stale(pairs: list[tuple[Path, str]]) -> list[Path]:
    """Generated files whose committed content differs from a fresh generation."""
    return [p for p, text in pairs if not p.exists() or p.read_text(encoding="utf-8") != text]


def main(argv: list[str]) -> int:
    check = "--check" in argv
    spec = openapi_text()
    with tempfile.TemporaryDirectory() as tmp:
        tmp_spec = Path(tmp) / "openapi.json"
        tmp_spec.write_text(spec, encoding="utf-8")
        types = types_text(tmp_spec)
    if check:
        bad = stale([(OPENAPI, spec), (TYPES, types)])
        for p in bad:
            print(f"out of date: {p} (run python tools/gen.py)")
        return 1 if bad else 0
    OPENAPI.parent.mkdir(parents=True, exist_ok=True)
    OPENAPI.write_text(spec, encoding="utf-8")
    TYPES.write_text(types, encoding="utf-8")
    print(f"wrote {OPENAPI}\nwrote {TYPES}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
